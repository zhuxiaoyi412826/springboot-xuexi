UPDATE novel n
SET chapter_count = COALESCE((SELECT COUNT(*) FROM chapter c WHERE c.novel_id = n.id), 0),
    word_count    = COALESCE((SELECT SUM(c.word_count) FROM chapter c WHERE c.novel_id = n.id), 0)
WHERE EXISTS (SELECT 1 FROM chapter c WHERE c.novel_id = n.id);
